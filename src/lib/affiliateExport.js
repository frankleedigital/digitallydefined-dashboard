// affiliateExport.js
// Export templates for the Affiliate Market Flip Calculator.
//
// Turns a flip-analysis result (from the FastAPI /affiliate/flip endpoint or the
// standalone calculator) into deliverables for three output surfaces:
//   • Markdown report  -> Notion paste or PDF print
//   • Plain-text pack  -> Gumroad digital product bundle (README / workbook)
//
// Every export includes the product analysis, affiliate network details,
// EPC + commission rate, the product-specific page outline, and the
// product-specific monetization plan.

const money = (v) =>
  new Intl.NumberFormat("en-US", { style: "currency", currency: "USD", maximumFractionDigits: 2 }).format(Number(v) || 0);

const pct = (rate) => `${((Number(rate) || 0) * 100).toFixed(1)}%`;

function listBlock(title, items) {
  if (!Array.isArray(items) || items.length === 0) return "";
  return `\n### ${title}\n\n${items.map((i) => `- ${i}`).join("\n")}\n`;
}

/** Build the core analysis summary shared by all exports. */
function normalizeResult(result = {}) {
  const pd = result.product_data || {};
  const rev = result.revenue_projection || {};
  return {
    product: result.product || pd.product || "—",
    niche: result.niche || "—",
    flipScore: result.flip_score ?? result.flipScore ?? 0,
    difficultyScore: result.difficulty_score ?? result.difficultyScore ?? 0,
    roi: result.roi ?? rev.roi ?? 0,
    usageSource: result.usage_source || result.usageSource || "manual",
    verdict: result.verdict || "—",
    network: pd.network || result.network || "—",
    category: pd.category || "—",
    price: pd.price ?? result.price ?? 0,
    commissionRate: pd.commission_rate ?? result.commission_rate ?? 0,
    epc: pd.epc ?? result.epc ?? 0,
    recurring: pd.recurring ?? result.recurring ?? false,
    difficulty: pd.difficulty || result.difficulty || "medium",
    keywords: result.recommended_keywords || result.keywords || [],
    angles: result.recommended_niche_angles || result.angles || [],
    outline: result.page_outline || result.outline || [],
    monetization: result.monetization_plan || result.monetization || [],
    action: result.seven_day_action_plan || result.action || [],
    revenueProjection: rev,
  };
}

/** Markdown report — paste into Notion or print to PDF. */
export function buildFlipMarkdown(result) {
  const r = normalizeResult(result);
  const srcLabel = r.usageSource === "catalog" ? "Verified catalog data" : r.usageSource === "llm" ? "AI-estimated" : "Manual input";

  let md = `# Affiliate Market Flip Report\n\n`;
  md += `**Product:** ${r.product}\n\n`;
  md += `**Niche:** ${r.niche}\n\n`;
  md += `---\n\n`;

  md += `## Scores\n\n| Metric | Value |\n|---|---|\n`;
  md += `| Flip Score | **${r.flipScore} / 100** |\n`;
  md += `| Difficulty Score | ${r.difficultyScore} / 100 |\n`;
  md += `| ROI Multiple | ${Number(r.roi).toFixed(2)}× |\n`;
  md += `| Data Source | ${srcLabel} |\n\n`;

  md += `## Verdict\n\n> ${r.verdict}\n\n`;

  md += `## Product Analysis\n\n| Field | Value |\n|---|---|\n`;
  md += `| Product | ${r.product} |\n`;
  md += `| Category | ${r.category} |\n`;
  md += `| Product Price | ${money(r.price)} |\n`;
  md += `| Commission Rate | ${pct(r.commissionRate)} |\n`;
  md += `| Commission / Sale | ${money(r.commissionRate * r.price)} |\n`;
  md += `| EPC (earnings per click) | ${money(r.epc)} |\n`;
  md += `| Affiliate Network | ${r.network} |\n`;
  md += `| Revenue Type | ${r.recurring ? "Recurring (monthly)" : "One-time payout"} |\n`;
  md += `| Estimated Difficulty | ${r.difficulty} |\n\n`;

  if (r.revenueProjection && Object.keys(r.revenueProjection).length) {
    md += `## Revenue Projection\n\n| Metric | Value |\n|---|---|\n`;
    md += `| Monthly Clicks | ${(r.revenueProjection.monthly_clicks || 0).toLocaleString()} |\n`;
    md += `| EPC | ${money(r.revenueProjection.epc ?? r.epc)} |\n`;
    md += `| Estimated Revenue | ${money(r.revenueProjection.estimated_revenue ?? 0)} |\n`;
    md += `| Commission / Sale | ${money(r.revenueProjection.commission_per_sale ?? 0)} |\n\n`;
  }

  md += listBlock("Recommended Keywords", r.keywords);
  md += listBlock("Recommended Niche Angles", r.angles);
  md += listBlock("Product-Specific Page Outline", r.outline);
  md += listBlock("Product-Specific Monetization Plan", r.monetization);
  md += listBlock("7-Day Action Plan", r.action);

  md += `\n---\n\n_Generated by the DigitallyDefined Affiliate Market Flip Calculator._\n`;
  return md;
}


/** Plain-text pack — for the Gumroad digital-product bundle. */
export function buildFlipPlainText(result) {
  const r = normalizeResult(result);
  let t = `AFFILIATE MARKET FLIP — PRODUCT PACK\n=====================================\n\n`;
  t += `Product:            ${r.product}\n`;
  t += `Niche:              ${r.niche}\n`;
  t += `Flip Score:         ${r.flipScore}/100\n`;
  t += `Difficulty Score:   ${r.difficultyScore}/100\n`;
  t += `ROI Multiple:       ${Number(r.roi).toFixed(2)}x\n`;
  t += `Affiliate Network:  ${r.network}\n`;
  t += `Category:           ${r.category}\n`;
  t += `Product Price:      ${money(r.price)}\n`;
  t += `Commission Rate:    ${pct(r.commissionRate)}\n`;
  t += `EPC:                ${money(r.epc)}\n`;
  t += `Revenue Type:       ${r.recurring ? "Recurring" : "One-time"}\n`;
  t += `Data Source:        ${r.usageSource}\n\n`;
  t += `VERDICT: ${r.verdict}\n\n`;

  const plain = (title, items) => {
    if (!Array.isArray(items) || !items.length) return "";
    let s = `\n${title.toUpperCase()}\n${"-".repeat(title.length)}\n`;
    items.forEach((i, idx) => { s += `${idx + 1}. ${i}\n`; });
    return s;
  };

  t += plain("Recommended Keywords", r.keywords);
  t += plain("Recommended Niche Angles", r.angles);
  t += plain("Product-Specific Page Outline", r.outline);
  t += plain("Product-Specific Monetization Plan", r.monetization);
  t += plain("7-Day Action Plan", r.action);
  return t;
}

/** Notion payload — passes the markdown as page content via createNotionPage(). */
export function buildFlipNotionPayload(result, databaseId) {
  const r = normalizeResult(result);
  return {
    databaseId,
    title: `Affiliate Flip — ${r.product} (${r.flipScore}/100)`,
    status: "Draft",
    content: buildFlipMarkdown(result),
  };
}

export default { buildFlipMarkdown, buildFlipPlainText, buildFlipNotionPayload };

